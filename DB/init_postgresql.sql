    ON identity.unresolved_detections (stage);

CREATE OR REPLACE FUNCTION identity.mark_face_registered()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE identity.students
    SET face_registered = true
    WHERE student_id = NEW.student_id;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_face_registered ON identity.face_embeddings;
CREATE TRIGGER trg_face_registered
    AFTER INSERT ON identity.face_embeddings
    FOR EACH ROW
    EXECUTE FUNCTION identity.mark_face_registered();

