CREATE OR REPLACE FUNCTION attendance.log_status_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO attendance.status_history (
            student_id, attendance_date, timetable_id,
            previous_status, new_status, modified_by
        ) VALUES (
            NEW.student_id, NEW.attendance_date, NEW.timetable_id,
            OLD.status, NEW.status, NEW.marked_by
        );
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_attendance_status_history ON attendance.records;
CREATE TRIGGER trg_attendance_status_history
    AFTER UPDATE ON attendance.records
    FOR EACH ROW
    EXECUTE FUNCTION attendance.log_status_change();

