-- SRM attendance — unified PostgreSQL schema
-- identity  = Phase 1 (capture, embeddings, identification events)
-- attendance = Phase 2 (timetable, marks, users, dashboard)
--
-- Apply after creating the database:
--   psql -U postgres -d srm_attendance -f DB/init_postgresql.sql
--
-- Changes vs the MariaDB dump (srmvec_ai_attendance.sql):
--   * One engine (Postgres + pgvector), two schemas — not MySQL + Postgres
--   * Embeddings only in identity.face_embeddings as VECTOR(512)
--   * No camera passwords / RTSP credentials
--   * university_id is the join key to the identification pipeline
--   * identification event_id is the ingest idempotency key
--   * Present/Late/Absent is not auto-forced by a duration trigger
--   * Summary functions use NULLIF to avoid divide-by-zero
--   * Defaulter generation upserts; it does not wipe history
--   * Consent / opted_out live on identity.students
--   * Unknown-face review does not store images by default

\set ON_ERROR_STOP on

BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS identity;
CREATE SCHEMA IF NOT EXISTS attendance;

COMMENT ON SCHEMA identity IS 'Phase 1: cameras, students, embeddings, identification events';
COMMENT ON SCHEMA attendance IS 'Phase 2: academic structure, attendance marks, dashboard users';

